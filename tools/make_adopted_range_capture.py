"""Prepare non-executable OLD capture candidates. Never deploy/build/run a browser."""
import argparse
import json
from pathlib import Path
import shlex
import subprocess
import sys

import adopted_range_contract as c
from adopted_range_contract import require, keys, canonical, read_json, file_id

NAME = 'step122-old-candidate'
PREFIX = 'step122_old_000118_v16'
LINEAGE = c.WORK/'json/step21_validation3_000118_v16_webgpu_visible_record_lineage.json'


def source_delivery():
    return {'/js/'+p.name:file_id(p) for p in sorted((c.VIEWER/'demo/js').glob('*.js'))}


def validate_candidate(value, *, current=True):
    if value.get('schema') == 'viewer-normal-capture-candidate-v2':
        from normal_range_capture import validate_candidate as validate_normal
        return validate_normal(value, current=current)
    if value.get('schema') == 'viewer-aligned-capture-candidate-v1':
        from aligned_range_capture import validate_candidate as validate_aligned
        return validate_aligned(value, current=current)
    keys(value,'schema execution_authorized review_required prefix mode range_input input source_delivery patches patch_origin generator_argv preparation')
    require(value['schema']=='viewer-old-capture-candidate-v1' and value['execution_authorized'] is False and
            value['review_required'] is True and value['prefix']==PREFIX,'capture_candidate')
    require(c.parse_mode(value['mode'])==dict(schema='viewer-old-source-bound-v1',mode='OLD',math_version=None,
                executed=False,terminated_pixel_count=None),'old_only')
    fixed=value['range_input']['fixed']
    require(value['input']['authority']==fixed['authority'] and value['input']['selection']==fixed['selection'], 'capture_input')
    require(value['input']==read_json(c.PRIOR/'step21-validation3-input.json'),'unchanged_adopted_input')
    from compare_adopted_range_capture import patch_plan
    require(value['patch_origin']==dict(path=str(LINEAGE),identity=file_id(LINEAGE)) and
            value['patches']==patch_plan(read_json(LINEAGE),fixed),'fixed_patches')
    require(value['generator_argv']==generator_args(), 'capture_generator_arguments')
    from prepare_adopted_range_capture import plan
    directory=c.safe_path(value['preparation']['directory'])
    require(directory.is_relative_to(c.REPORTS) and value['preparation']==plan(directory),'preparation_plan')
    if current:
        c.preflight(value['range_input'])
        require(value['source_delivery']==source_delivery(),'source_changed')
    require(bool(value['source_delivery']) and all(k.startswith('/js/') and set(v)=={'size','sha256'}
                for k,v in value['source_delivery'].items()),'source_delivery_membership')


def generator_args():
    evidence=read_json(c.PRIOR/'step21-validation3-preparation-evidence.json')
    argv=evidence['capture_generator_argv'][3:]
    require(argv[-2]=='--out' and '--canonical-src-indices' in argv,'inherited_argv')
    argv=argv[:-2]
    for option,value in (('--step',PREFIX),('--phase-step','viewer-step122-old')):
        argv[argv.index(option)+1]=value
    # Every other flag, including all seven representatives, remains unchanged.
    return argv


def write(path,data):
    path=c.safe_path(path)
    with path.open('xb') as f:f.write(data)
    require(path.read_bytes()==data and bool(data),'candidate_readback')


def wrapper(value, *, name=NAME, prefix=PREFIX):
    template=(c.PRIOR/'step21-validation3-browser.js').read_text()
    template=template.replace('step21_validation3_000118_v16',prefix).replace('step21-validation3',name)
    template=template.replace('step21Validation3','step122OldCandidate').replace('Step21-validation3','Step122-OLD-candidate')
    # Keep the reviewed initial wait, fresh request wait, failures and downloads.
    template=template.replace('export async function run() {','export async function run(authorization) {')
    template=template.replace('  let raw = null;', '  let raw = null;\n  let comparisonSupport = null;')
    template=template.replace('  let downloaded = false;', '  let downloaded = false;\n  let restoreDownload = null;')
    anchor='    // Let the normal default-scene fetch finish'
    guard='''    const bytes = await (await fetch('/NAME/candidate.json', {cache:'no-store'})).arrayBuffer();
    const sha = async b => Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',b)),x=>x.toString(16).padStart(2,'0')).join('');
    if (await sha(bytes) !== 'DIGEST') throw new Error('Candidate changed; no fallback');
    const candidate = JSON.parse(new TextDecoder().decode(bytes));
    // Candidate is immutable and itself grants no execution authority. No such
    // authorization object is generated by preparation; it requires later review.
    if (authorization?.execution_authorized !== true || authorization?.candidate_sha256 !== await sha(bytes) ||
        authorization?.mode !== 'OLD') throw new Error('Separate OLD execution authorization required');
    const delivery = {};
    for (const [url, id] of Object.entries(candidate.source_delivery)) {
      const response = await fetch(url, {cache:'no-store'});
      if (!response.ok) throw new Error('Missing served source: '+url);
      const data = await response.arrayBuffer();
      const got = {size:data.byteLength, sha256:await sha(data)};
      if (got.size !== id.size || got.sha256 !== id.sha256) throw new Error('Source/delivery mismatch: '+url);
      delivery[url] = got;
    }
    comparisonSupport = {schema:'viewer-range-capture-support-v1',
      candidate_identity:{size:bytes.byteLength,sha256:await sha(bytes)},
      mode:{...candidate.mode,executed:true},delivery,json_members:{}};
    const originalDownload = debug.downloadJsonDebug;
    debug.downloadJsonDebug = async (data, name) => {
      if (!name.startsWith(candidate.prefix+'_') || comparisonSupport.json_members[name])
        throw new Error('Unexpected or duplicate capture member');
      const serialized = new TextEncoder().encode(JSON.stringify(data,null,2));
      const result = await originalDownload.call(debug,data,name);
      if (result.fileName !== name || result.byteLength !== serialized.byteLength)
        throw new Error('JSON download identity mismatch');
      comparisonSupport.json_members[name] = {size:serialized.byteLength,sha256:await sha(serialized)};
      return result;
    };
    restoreDownload = () => { debug.downloadJsonDebug = originalDownload; };
'''.replace('NAME',name).replace('DIGEST',c.identity(canonical(value))['sha256'])
    require(template.count(anchor)==1 and template.count('    inputContext: context,')==1,'wrapper_template')
    template=template.replace(anchor,guard+anchor).replace('    inputContext: context,','    comparisonSupport, inputContext: context,')
    template=template.replace('  const result = {','  restoreDownload?.();\n  const result = {')
    return template


def prepare_script(directory):
    return '''#!/usr/bin/env bash
set -eu
if [ "$#" -ne 2 ] || [ "$1" != '--authorization' ]; then
    printf '%s\\n' 'STOP: separate reviewed preparation authorization required; nothing changed.'
    exit 1
fi
exec PYTHON -B TOOL --directory DIRECTORY --authorization "$2"
'''.replace('PYTHON',shlex.quote(c.PYTHON)).replace('TOOL',shlex.quote(str(c.VIEWER/'tools/prepare_adopted_range_capture.py'))).replace('DIRECTORY',shlex.quote(str(directory)))


def generate(directory, range_input):
    from compare_adopted_range_capture import patch_plan
    from prepare_adopted_range_capture import plan
    c.preflight(range_input)
    directory=c.safe_path(directory)
    require(directory.is_relative_to(c.REPORTS) and not directory.exists(),'exclusive_candidate_directory')
    value=dict(schema='viewer-old-capture-candidate-v1',execution_authorized=False,review_required=True,
        prefix=PREFIX,mode=dict(schema='viewer-old-source-bound-v1',mode='OLD',math_version=None,
                              executed=False,terminated_pixel_count=None),range_input=range_input,
        input=read_json(c.PRIOR/'step21-validation3-input.json'),source_delivery=source_delivery(),
        patches=patch_plan(read_json(LINEAGE),range_input['fixed']),
        patch_origin=dict(path=str(LINEAGE),identity=file_id(LINEAGE)),generator_argv=generator_args(),
        preparation=plan(directory))
    validate_candidate(value)
    directory.mkdir()
    write(directory/'candidate.json',canonical(value))
    write(directory/(NAME+'-input.json'),canonical(value['input']))
    write(directory/(NAME+'-browser.js'),wrapper(value).encode())
    # Call the existing generator in-process; no browser or server execution.
    import make_capture_commands as generator
    original=sys.argv
    try:
        sys.argv=['make_capture_commands.py',*value['generator_argv']]
        generated=generator.build_commands(generator.parse_args())
    finally:sys.argv=original
    generated+='\nexport { genericProductionCaptureResult, genericProductionPngCaptureStatus, genericProductionPngCaptureResult };\n'
    write(directory/(NAME+'-capture.js'),generated.encode())
    write(directory/'prepare-candidate.sh',prepare_script(directory).encode())
    members={p.name:file_id(p) for p in sorted(directory.iterdir())}
    write(directory/'files.json',canonical(dict(schema='viewer-capture-candidate-files-v1',members=members,
          executable=False,review_required=True,delivery_verified=False,browser_executed=False)))
    return value


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory',required=True);parser.add_argument('--range-input',required=True)
    args=parser.parse_args()
    generate(Path(args.directory),read_json(args.range_input))
    print('Unapproved OLD candidate saved; no deploy/browser execution.')


if __name__=='__main__':main()
